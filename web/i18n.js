  var lang = "en";
  function find(id) { return LANGS.filter(function (l) { return l.id === id; })[0] || null; }

  function detect() {
    try {
      if (window.TVOS && typeof window.TVOS.language === "function") {
        var l = (window.TVOS.language() || "").toLowerCase();
        if (l.indexOf("fr") === 0) return "fr";
        if (l.indexOf("en") === 0) return "en";
      }
    } catch (e) {}
    try {
      var nav = (navigator.language || "").toLowerCase();
      if (nav.indexOf("fr") === 0) return "fr";
      if (nav.indexOf("en") === 0) return "en";
    } catch (e) {}
    return "en";
  }

  function set(id) {
    lang = find(id) ? id : detect();
    try { document.documentElement.lang = find(lang).locale; } catch (e) {}
    return lang;
  }

  function t(key, vars) {
    var s = (lang === "fr" && S.fr[key]) || (lang === "en" && S.en[key]) || S.fr[key] || S.en[key];
    if (s == null) s = key;
    if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
    return s;
  }

  window.I18N = {
    t: t,
    set: set,
    detect: detect,
    lang: function () { return lang; },
    locale: function () { return find(lang) ? find(lang).locale : "fr-FR"; },
    langs: LANGS,
    strings: S
  };
